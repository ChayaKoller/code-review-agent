"""core/docker_runner.py: הרצת קוד של הפרויקט הנבדק, ורק בתוך Docker.

הרעיון: כל פקודה רצה בקונטיינר חד-פעמי (--rm) בלי רשת, עם מגבלות זיכרון, CPU
ותהליכים, בלי הרשאות מיוחדות ועם מערכת קבצים לקריאה בלבד. הדבר היחיד שנטען
אליו הוא ההעתק של ה-sandbox (בכתיבה). המקור לעולם לא נטען.

ספריות: בלי רשת אי אפשר להתקין בזמן ההרצה, ולכן הספריות של הריפו נכנסות ל-image.
לכל ריפו נבנה image מעל image הבסיס (docker/Dockerfile), מתוך קבצי requirements
שבשורש הריפו (ואופציונלית חבילות נוספות שהמשתמש מציין). הוא נבנה פעם אחת
ונשמר לפי חתימה של התוכן, כך שהרצה שנייה על אותן תלויות לא בונה מחדש.
הבנייה עצמה כן צריכה רשת (pip), אבל היא קורית רק ב-Docker.

ריפו שמוגדר כחבילה (pyproject.toml עם [project] או [build-system], setup.py, setup.cfg):
הריפו עצמו מותקן ב-image עם התלויות שלו ועם ה-extras של הטסטים (test/tests/testing).
כך ריפו שהורד מקישור מקבל את הספריות שלו גם בלי requirements. בהרצה PYTHONPATH מצביע
על ההעתק (/work/src ו-/work), ולכן הקוד שנבדק הוא תמיד ההעתק עם התיקון ולא הגרסה שהותקנה.
אם ההתקנה של הריפו נכשלת, הבנייה ממשיכה (רק התלויות מ-requirements), והטסטים יגלו ספריות חסרות.

מגבלות ידועות: נקראים רק קבצים בשורש הריפו. שורות כמו `-e .` או הפניות `-r` לקבצים
בתיקיות אחרות בתוך requirements לא נתמכות. גרסת Python אחת לכל ה-images.

ב-core אין print. הפונקציות מחזירות נתונים או זורקות DockerError.
"""
from __future__ import annotations

import hashlib
import json
import re
import shutil
import subprocess
import tempfile
import uuid
from dataclasses import dataclass, field
from pathlib import Path

from core import config

EXTRA_REQUIREMENTS_NAME = "cra_extra_requirements.txt"
NO_TESTS_RETURNCODE = 5  # pytest: לא נאספו טסטים

# Dockerfile שנוצר לכל ריפו: image הבסיס + הספריות שלו.
# USER root כדי ש-pip יתקין לכל המערכת (בהרצה HOME משתנה, ולכן user-site לא יימצא).
_DEPS_DOCKERFILE = """\
# generated by core/docker_runner.py: base image + the libraries of the reviewed repo
FROM @@BASE@@
ARG PIP_EXTRA_ARGS=""
USER root
COPY reqs/ /tmp/reqs/
RUN cd /tmp/reqs && @@INSTALL@@ && rm -rf /tmp/reqs
@@PROJECT@@USER runner
"""

# מתקין את הריפו עצמו (עם התלויות שלו). כישלון לא עוצר את הבנייה: מדפיס סימן ומוחק.
_PROJECT_STEP = """COPY src/ /tmp/src/
RUN pip install ${PIP_EXTRA_ARGS} "/tmp/src[@@EXTRAS@@]" || echo "CRA_PROJECT_INSTALL_FAILED"; rm -rf /tmp/src
"""
_PACKAGE_MARKERS = ("[project]", "[build-system]", "[tool.poetry]")

# בודק קומפילציה בלי להריץ את הקוד ובלי לכתוב קבצים (בלי .pyc).
# מדפיס שורת JSON אחת: {קובץ: {"line": מספר, "msg": הודעה}} (ריק = הכול תקין)
_COMPILE_SCRIPT = """\
import json, sys
errors = {}
for name in sys.argv[1:]:
    try:
        with open(name, encoding="utf-8") as fh:
            compile(fh.read(), name, "exec")
    except SyntaxError as e:
        errors[name] = {"line": e.lineno, "msg": e.msg}
    except Exception as e:
        errors[name] = {"line": None, "msg": type(e).__name__ + ": " + str(e)}
print(json.dumps(errors))
"""

# pytest 5+ כותב FAILED, ו-pytest ישן (3.x, בריפוזיטוריז של ה-test set) כותב FAIL
_FAILED_LINE = re.compile(r"^(FAILED|FAIL|ERROR) (\S+)", re.MULTILINE)
_MISSING_MODULE = re.compile(r"ModuleNotFoundError: No module named '([^']+)'")


class DockerError(RuntimeError):
    """Docker לא זמין, ה-image חסר או נכשל בבנייה, או שההרצה נכשלה מסיבה שאינה קשורה לטסטים."""


# ------------------------------------------------------------- תוצאות


def file_of_test(test_id: str) -> str:
    """'tests/test_a.py::test_x' -> 'tests/test_a.py'"""
    return test_id.split("::")[0]


@dataclass
class TestRun:
    __test__ = False  # pytest: זו לא מחלקת טסטים

    passed: bool  # כל הטסטים עברו
    failed: list[str] = field(default_factory=list)  # מזהי טסטים שנכשלו או שגו
    timed_out: bool = False
    returncode: int | None = None
    no_tests: bool = False  # pytest לא מצא טסטים להרצה
    missing_modules: list[str] = field(default_factory=list)  # ספריות שחסרות ב-image
    output: str = ""  # הפלט המלא של pytest, לדיבוג

    @property
    def failed_files(self) -> list[str]:
        return sorted({file_of_test(t) for t in self.failed})


@dataclass
class CompileResult:
    ok: bool
    errors: dict[str, dict] = field(default_factory=dict)  # קובץ -> {"line": ..., "msg": ...}


@dataclass
class _Raw:
    returncode: int | None
    stdout: str = ""
    stderr: str = ""
    timed_out: bool = False

    @property
    def output(self) -> str:
        return self.stdout + self.stderr


# ------------------------------------------------------------- עזרים


def _to_text(value) -> str:
    if value is None:
        return ""
    if isinstance(value, bytes):
        return value.decode("utf-8", "replace")
    return value


def _clip(text: str) -> str:
    limit = config.MAX_OUTPUT_CHARS
    return text if len(text) <= limit else "...(הפלט קוצר)...\n" + text[-limit:]


def find_requirement_files(root: str | Path) -> list[str]:
    """קבצי requirements מוכרים בשורש הריפו (שמות בלבד, בסדר קבוע)."""
    root = Path(root)
    return [name for name in config.REQUIREMENT_FILE_NAMES if (root / name).is_file()]


def find_project_files(root: str | Path) -> list[str]:
    """קבצי ההגדרה של הריפו כחבילה. pyproject.toml שיש בו רק הגדרות כלים (למשל pytest) לא נחשב."""
    if not config.DOCKER_INSTALL_PROJECT:
        return []
    root = Path(root)
    found = []
    for name in config.PROJECT_METADATA_FILES:
        path = root / name
        if not path.is_file():
            continue
        if name == "pyproject.toml":
            text = path.read_text(encoding="utf-8", errors="replace")
            if not any(marker in text for marker in _PACKAGE_MARKERS):
                continue
        found.append(name)
    return found


def _copy_project(root: Path, dest: Path) -> None:
    """מעתיק את הריפו להקשר הבנייה, בלי .git ובלי תיקיות שמתעלמים מהן."""
    shutil.copytree(
        root,
        dest,
        ignore=shutil.ignore_patterns(".git", *config.COPY_IGNORE_DIRS, "*.pyc"),
        copy_function=shutil.copyfile,  # בלי סימון קריאה-בלבד
    )


def _clean_packages(extra_packages: list[str] | None) -> list[str]:
    packages = []
    for item in extra_packages or []:
        pkg = item.strip()
        if not pkg:
            continue
        # שורה שמתחילה ב-"-" היא אפשרות של pip (למשל --index-url), לא שם חבילה
        if pkg.startswith("-") or "\n" in pkg or "\r" in pkg:
            raise ValueError(f"שם חבילה לא תקין: {item!r}")
        packages.append(pkg)
    return sorted(set(packages))


# ------------------------------------------------------------- הרצה


class DockerRunner:
    """מריץ פקודות Docker. הפרמטר run מאפשר להחליף את subprocess.run בבדיקות."""

    def __init__(self, image: str | None = None, run=subprocess.run):
        self.image = image or config.DOCKER_IMAGE  # image הבסיס
        self._run = run

    # --- זמינות ובנייה ---

    def _call(self, cmd: list[str], timeout: int) -> subprocess.CompletedProcess:
        try:
            return self._run(
                cmd,
                capture_output=True,
                text=True,
                encoding="utf-8",
                errors="replace",
                timeout=timeout,
            )
        except FileNotFoundError:
            raise DockerError(
                "Docker לא נמצא. להתקין Docker Desktop ולוודא שהפקודה docker עובדת בטרמינל"
            ) from None

    def is_available(self) -> bool:
        """האם Docker מותקן וה-daemon רץ."""
        try:
            proc = self._call(["docker", "version", "--format", "{{.Server.Version}}"], 20)
        except (DockerError, subprocess.TimeoutExpired):
            return False
        return proc.returncode == 0

    def image_exists(self, image: str | None = None) -> bool:
        proc = self._call(["docker", "image", "inspect", image or self.image], 30)
        return proc.returncode == 0

    def _build(self, cmd: list[str], what: str, deps: bool = False) -> None:
        try:
            proc = self._call(cmd, config.DOCKER_BUILD_TIMEOUT_SECONDS)
        except subprocess.TimeoutExpired:
            raise DockerError(f"בניית ה-image ({what}) לקחה יותר מדי זמן") from None
        if proc.returncode == 0:
            return
        tail = "\n".join((proc.stdout + proc.stderr).strip().splitlines()[-15:])
        hints = []
        if re.search(r"certificate|ssl", tail, re.IGNORECASE):
            hints.append(
                "נראה כמו בעיית תעודה (נטפרי). אפשר להגדיר ב-.env: "
                "DOCKER_PIP_EXTRA_ARGS=--trusted-host pypi.org --trusted-host files.pythonhosted.org"
            )
        if deps and re.search(r"Invalid requirement|requirements file|No such file", tail):
            hints.append(
                "אם בקובץ requirements יש שורות כמו -e . או הפניות (-r) לקבצים בתיקיות אחרות, "
                "הן לא נתמכות כרגע"
            )
        extra = ("\n" + "\n".join(hints)) if hints else ""
        raise DockerError(f"בניית ה-image ({what}) נכשלה:\n{tail}{extra}")

    def build_image(self) -> None:
        """בונה את image הבסיס (Python + pytest). דורש רשת."""
        cmd = [
            "docker", "build", "-t", self.image,
            "--build-arg", f"PYTHON_VERSION={config.DOCKER_PYTHON_VERSION}",
            "--build-arg", f"PIP_EXTRA_ARGS={config.DOCKER_PIP_EXTRA_ARGS}",
            "-f", str(config.DOCKER_DIR / "Dockerfile"),
            str(config.DOCKER_DIR),
        ]  # fmt: skip
        self._build(cmd, "בסיס")

    def ensure_image(self) -> None:
        """image הבסיס קיים. אם לא, בונים אותו."""
        if not self.is_available():
            raise DockerError("Docker לא רץ. להפעיל את Docker Desktop ולנסות שוב")
        if not self.image_exists():
            self.build_image()

    # --- הספריות של הריפו ---

    def deps_image_tag(self, root: str | Path, extra_packages: list[str] | None = None) -> str | None:
        """שם ה-image של הריפו, לפי חתימה של התלויות שלו. None = אין תלויות (משתמשים בבסיס)."""
        root = Path(root)
        files = find_requirement_files(root)
        project = find_project_files(root)
        packages = _clean_packages(extra_packages)
        if not files and not project and not packages:
            return None
        # החתימה רק על קבצי ההגדרה, לא על הקוד: תיקון בקוד לא גורם לבנייה מחדש
        digest = hashlib.sha256()
        digest.update(self.image.encode("utf-8"))
        for name in files + project:
            digest.update(b"\0file\0" + name.encode("utf-8") + b"\0")
            digest.update((root / name).read_bytes())
        for pkg in packages:
            digest.update(b"\0pkg\0" + pkg.encode("utf-8"))
        return f"{config.DOCKER_DEPS_IMAGE_REPO}:{digest.hexdigest()[:12]}"

    def _build_deps_image(self, root: Path, tag: str, extra_packages: list[str] | None) -> None:
        self.ensure_image()
        files = find_requirement_files(root)
        project = find_project_files(root)
        packages = _clean_packages(extra_packages)
        with tempfile.TemporaryDirectory(prefix="cra_ctx_") as tmp:
            ctx = Path(tmp)
            reqs = ctx / "reqs"
            reqs.mkdir()
            names = []
            for name in files:
                shutil.copyfile(root / name, reqs / name)  # copyfile: בלי סימון קריאה-בלבד
                names.append(name)
            if packages:
                (reqs / EXTRA_REQUIREMENTS_NAME).write_text("\n".join(packages) + "\n", encoding="utf-8")
                names.append(EXTRA_REQUIREMENTS_NAME)
            install = "pip install ${PIP_EXTRA_ARGS} " + " ".join(f"-r {n}" for n in names) if names else "true"
            project_step = ""
            if project:
                _copy_project(root, ctx / "src")
                project_step = _PROJECT_STEP.replace("@@EXTRAS@@", ",".join(config.PROJECT_TEST_EXTRAS))
            dockerfile = (
                _DEPS_DOCKERFILE.replace("@@BASE@@", self.image)
                .replace("@@INSTALL@@", install)
                .replace("@@PROJECT@@", project_step)
            )
            (ctx / "Dockerfile").write_text(dockerfile, encoding="utf-8")
            cmd = [
                "docker", "build", "-t", tag,
                "--build-arg", f"PIP_EXTRA_ARGS={config.DOCKER_PIP_EXTRA_ARGS}",
                "-f", str(ctx / "Dockerfile"),
                str(ctx),
            ]  # fmt: skip
            self._build(cmd, "הספריות של הריפו", deps=True)

    def prepare_image(self, sandbox_path: str | Path, extra_packages: list[str] | None = None) -> str:
        """מחזיר את שם ה-image להרצה: הבסיס, או image עם הספריות של הריפו.
        ה-image נבנה פעם אחת (איטי) ואחר כך נשמר. כדאי לקרוא לזה מראש כדי להציג למשתמש "בונה סביבה"."""
        root = Path(sandbox_path)
        tag = self.deps_image_tag(root, extra_packages)
        if tag is None:
            return self.image
        if not self.image_exists(tag):
            self._build_deps_image(root, tag, extra_packages)
        return tag

    # --- הרצה בקונטיינר ---

    def _remove_container(self, name: str) -> None:
        """timeout עוצר רק את הפקודה docker ולא את הקונטיינר, ולכן עוצרים אותו ידנית."""
        try:
            proc = self._call(["docker", "rm", "-f", name], 60)
        except subprocess.TimeoutExpired:
            proc = None
        if proc is None or (proc.returncode != 0 and "No such container" not in (proc.stderr or "")):
            raise DockerError(f"לא הצלחתי לעצור את הקונטיינר {name}. להריץ ידנית: docker rm -f {name}")

    def _run_in_container(self, sandbox_path: str | Path, image: str, command: list[str], timeout: int) -> _Raw:
        src = Path(sandbox_path).resolve()
        if not src.is_dir():
            raise DockerError(f"ההעתק לא קיים: {src}")
        if "," in str(src) or '"' in str(src):
            raise DockerError(f"נתיב עם פסיק או גרשיים לא נתמך בהעתק: {src}")
        name = f"{config.DOCKER_CONTAINER_PREFIX}{uuid.uuid4().hex[:8]}"
        cmd = [
            "docker", "run", "--rm", "--name", name,
            "--network", "none",
            "--memory", config.DOCKER_MEMORY, "--memory-swap", config.DOCKER_MEMORY,
            "--cpus", config.DOCKER_CPUS, "--pids-limit", config.DOCKER_PIDS_LIMIT,
            "--cap-drop", "ALL", "--security-opt", "no-new-privileges",
            "--read-only", "--tmpfs", "/tmp:rw,size=128m",
            "-e", "HOME=/tmp", "-e", "PYTHONDONTWRITEBYTECODE=1", "-e", "PYTHONIOENCODING=utf-8",
            # הקוד מההעתק קודם לגרסה שהותקנה ב-image (חשוב לריפו במבנה src/)
            "-e", "PYTHONPATH=/work/src:/work",
            "--mount", f"type=bind,source={src},target=/work",
            "-w", "/work", image, *command,
        ]  # fmt: skip
        try:
            proc = self._call(cmd, timeout)
        except subprocess.TimeoutExpired as exc:
            self._remove_container(name)
            return _Raw(None, stdout=_clip(_to_text(exc.stdout)), timed_out=True)
        if proc.returncode == 125:  # Docker עצמו נכשל (לא הפקודה שבתוך הקונטיינר)
            err = _clip(proc.stderr or "").strip()
            hint = ""
            if re.search(r"Unable to find image|pull access denied|No such image", err):
                hint = f"\nה-image '{image}' לא קיים. לבנות אותו: python -m scripts.docker_check"
            raise DockerError(f"Docker סירב להריץ את הקונטיינר:\n{err}{hint}")
        return _Raw(proc.returncode, stdout=_clip(proc.stdout or ""), stderr=_clip(proc.stderr or ""))

    def run_tests(
        self,
        sandbox_path: str | Path,
        timeout: int | None = None,
        extra_packages: list[str] | None = None,
    ) -> TestRun:
        """מריץ pytest בתוך קונטיינר ומחזיר אילו טסטים נכשלו."""
        image = self.prepare_image(sandbox_path, extra_packages)
        command = ["python", "-m", "pytest", "-q", "-rfE", "-p", "no:cacheprovider"]
        raw = self._run_in_container(sandbox_path, image, command, timeout or config.TEST_TIMEOUT_SECONDS)
        if raw.timed_out:
            return TestRun(passed=False, timed_out=True, output=raw.output)
        return TestRun(
            passed=raw.returncode == 0,
            failed=sorted({m.group(2) for m in _FAILED_LINE.finditer(raw.output)}),
            returncode=raw.returncode,
            no_tests=raw.returncode == NO_TESTS_RETURNCODE,
            missing_modules=sorted(set(_MISSING_MODULE.findall(raw.output))),
            output=raw.output,
        )

    def check_compile(
        self,
        sandbox_path: str | Path,
        files: list[str],
        timeout: int | None = None,
    ) -> CompileResult:
        """בודק שהקבצים מתקמפלים (בלי להריץ אותם). לא צריך את הספריות של הריפו."""
        if not files:
            return CompileResult(ok=True)
        command = ["python", "-c", _COMPILE_SCRIPT, *files]
        raw = self._run_in_container(
            sandbox_path, self.image, command, timeout or config.DOCKER_COMPILE_TIMEOUT_SECONDS
        )
        if raw.timed_out:
            raise DockerError("בדיקת הקומפילציה לא הסתיימה בזמן")
        if raw.returncode != 0:
            raise DockerError(f"בדיקת הקומפילציה נכשלה (קוד {raw.returncode}):\n{raw.output[-1000:]}")
        lines = raw.stdout.strip().splitlines()
        try:
            errors = json.loads(lines[-1]) if lines else {}
        except json.JSONDecodeError:
            raise DockerError(f"פלט לא צפוי מבדיקת הקומפילציה:\n{raw.output[-500:]}") from None
        return CompileResult(ok=not errors, errors=errors)
